//   5_    八分音符（半拍），同一拍裡連著兩個會自動用符槓連起來
//   5.    附點四分音符（一拍半），通常後面接一個八分音符：「3. 2_」
//   -     前一個音再延長一拍：「5 -」二分音符、「1 - -」附點二分音符、「1 - - -」全音符
